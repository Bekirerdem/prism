/// How far back an attestation may reach. `period_spent` sums hourly buckets, and a
/// bucket old enough to be archived would silently read as zero — making a stale period
/// look cheaper than it was. Well inside the persistent min-TTL, so the sum stays honest.
const MAX_PERIOD_LOOKBACK: u64 = 7;

/// BN254 scalar field order `r`, big-endian.
///
/// `Bn254Fr::from_bytes` reduces modulo `r`, so a field element has many byte
/// encodings: `x`, `x + r`, `x + 2r`, ... all denote the same element. The pairing
/// check cannot tell them apart, but anything that keys on the raw bytes — the
/// period bookkeeping below — can. Only values strictly below `r` are canonical.
const BN254_FR_MODULUS: [u8; 32] = [
    0x30, 0x64, 0x4E, 0x72, 0xE1, 0x31, 0xA0, 0x29, 0xB8, 0x50, 0x45, 0xB6, 0x81, 0x81, 0x58, 0x5D,
    0x28, 0x33, 0xE8, 0x48, 0x79, 0xB9, 0x70, 0x91, 0x43, 0xE1, 0xF5, 0x93, 0xF0, 0x00, 0x00, 0x01,
];

/// Whether a 32-byte public signal is the canonical encoding of its field element.
/// Big-endian compare against `r`; equal to `r` is not canonical (it is zero).
fn is_canonical(v: &BytesN<32>) -> bool {
    let b = v.to_array();
    let mut i = 0usize;
    while i < 32 {
        if b[i] < BN254_FR_MODULUS[i] {
            return true;
        }
        if b[i] > BN254_FR_MODULUS[i] {
            return false;
        }
        i += 1;
    }
    false
}

/// True if the big-endian 32-byte value is < 2^max_bits.
fn fits_bits(v: &BytesN<32>, max_bits: u32) -> bool {
    let arr = v.to_array();
    let full_zero_bytes = ((256 - max_bits) / 8) as usize;
    let rem = (256 - max_bits) % 8;
    for i in 0..full_zero_bytes {
        if arr[i] != 0 {
            return false;
        }
    }
    if rem > 0 && (arr[full_zero_bytes] >> (8 - rem)) != 0 {
        return false;
    }
    true
}

/// A non-negative `i128` as the 32-byte big-endian field element the circuit sees.
/// Negative values have no field encoding here and are refused by the caller.
fn field_from_i128(env: &Env, v: i128) -> BytesN<32> {
    let mut out = [0u8; 32];
    out[16..32].copy_from_slice(&v.to_be_bytes());
    BytesN::from_array(env, &out)
}

/// A field element as a day number, or `None` if it does not fit 64 bits.
fn u64_from_field(v: &BytesN<32>) -> Option<u64> {
    let b = v.to_array();
    let mut i = 0usize;
    while i < 24 {
        if b[i] != 0 {
            return None;
        }
        i += 1;
    }
    let mut n = 0u64;
    let mut j = 24usize;
    while j < 32 {
        n = (n << 8) | b[j] as u64;
        j += 1;
    }
    Some(n)
}

