fn vk(env: &Env) -> VerificationKey {
    let alpha = Bn254G1Affine::from_array(env, &VK_ALPHA);
    let beta = Bn254G2Affine::from_array(env, &VK_BETA);
    let gamma = Bn254G2Affine::from_array(env, &VK_GAMMA);
    let delta = Bn254G2Affine::from_array(env, &VK_DELTA);

    let mut ic = Vec::new(env);
    for p in VK_IC.iter() {
        ic.push_back(Bn254G1Affine::from_array(env, p));
    }

    VerificationKey { alpha, beta, gamma, delta, ic }
}

#[contract]
pub struct ComplianceVerifier;

#[contractimpl]
impl ComplianceVerifier {
    pub fn verify_proof(
        env: Env,
        proof: Proof,
        pub_signals: Vec<Bn254Fr>,
    ) -> Result<bool, Groth16Error> {
        let bn = env.crypto().bn254();
        let vk = vk(&env);

        if pub_signals.len() + 1 != vk.ic.len() {
            return Err(Groth16Error::MalformedVerifyingKey);
        }

        let mut vk_x = vk.ic.get(0).unwrap();
        for (s, v) in pub_signals.iter().zip(vk.ic.iter().skip(1)) {
            let prod = bn.g1_mul(&v, &s);
            vk_x = bn.g1_add(&vk_x, &prod);
        }

        let neg_a = -proof.a;
        let vp1 = soroban_sdk::vec![&env, neg_a, vk.alpha, vk_x, proof.c];
        let vp2 = soroban_sdk::vec![&env, proof.b, vk.beta, vk.gamma, vk.delta];

        Ok(bn.pairing_check(vp1, vp2))
    }

    /// Verify a compliance proof for `treasury`'s closed period and, on success, emit
    /// `attested`. Traps on any mismatch — the whole point is that an attestation only
    /// exists when every claim in it survived a check against the chain.
    ///
    /// proof_bytes  = a(64) || b(128) || c(64)      = 256 bytes
    /// public_bytes = 13 field elements x 32 bytes  = 416 bytes
    ///   layout: [dailyLimit, perTaskLimit, whitelistRoot, periodId, periodSpent, commitments[8]]
    pub fn verify(env: Env, treasury: Address, proof_bytes: Bytes, public_bytes: Bytes) {
        // ---- INPUT SHAPE: fail closed with a typed error, not an opaque slice panic ----
        if proof_bytes.len() != PROOF_BYTES {
            panic_with_error!(&env, VerifierError::InvalidProofLength);
        }
        if public_bytes.len() != PUBLIC_BYTES {
            panic_with_error!(&env, VerifierError::InvalidPublicInputLength);
        }

        // ---- CANONICAL ENCODING: one field element, one byte string ----
        // Without this, anything keyed on raw bytes can be fooled by resubmitting the
        // same element as `x + r`: identical to the pairing check, different to us.
        let mut sig: u32 = 0;
        while sig < SIGNALS {
            let fr: BytesN<32> = public_bytes
                .slice(sig * 32..sig * 32 + 32)
                .try_into()
                .unwrap();
            if !is_canonical(&fr) {
                panic_with_error!(&env, VerifierError::NonCanonicalSignal);
            }
            sig += 1;
        }

        // ---- WHO IS ASKING: only the treasury's owner may attest on its behalf ----
        let t = TreasuryClient::new(&env, &treasury);
        let cfg = t.get_config();
        cfg.admin.require_auth();

        // ---- POLICY BINDING: the limits come from the treasury, not from a stored copy ----
        // A negative limit has no field encoding; the treasury's constructor rejects those,
        // so seeing one here means the counterparty is not a treasury we can reason about.
        if cfg.daily_limit < 0 || cfg.per_task_limit < 0 {
            panic_with_error!(&env, VerifierError::PolicyMismatch);
        }
        let daily: BytesN<32> = public_bytes.slice(0..32).try_into().unwrap();
        let per_task: BytesN<32> = public_bytes.slice(32..64).try_into().unwrap();
        if daily != field_from_i128(&env, cfg.daily_limit)
            || per_task != field_from_i128(&env, cfg.per_task_limit)
        {
            panic_with_error!(&env, VerifierError::PolicyMismatch);
        }

        // The circuit compares with LessEqThan(nBits+4=68) for the daily limit and
        // LessEqThan(nBits=64) per task. A limit wider than its comparator makes that
        // comparison meaningless — the policy check would silently stop biting — so a
        // treasury configured beyond the circuit's range cannot be attested for at all.
        // Checked here rather than at deploy time because `set_limits` can move them.
        if !fits_bits(&daily, 68) || !fits_bits(&per_task, 64) {
            panic_with_error!(&env, VerifierError::LimitExceedsCircuitRange);
        }

        // The payee root is the treasury's own published policy statement.
        let root: BytesN<32> = public_bytes.slice(64..96).try_into().unwrap();
        match t.whitelist_root() {
            Some(on_chain) => {
                if root != on_chain {
                    panic_with_error!(&env, VerifierError::PolicyMismatch);
                }
            }
            None => panic_with_error!(&env, VerifierError::WhitelistRootUnset),
        }

        // ---- PERIOD: a closed, recent day, and strictly after the last one attested ----
        let period_fr: BytesN<32> = public_bytes.slice(96..128).try_into().unwrap();
        let period = match u64_from_field(&period_fr) {
            Some(p) => p,
            None => panic_with_error!(&env, VerifierError::PeriodNotClosed),
        };
        let current = env.ledger().timestamp() / SECONDS_PER_DAY;
        // An open period's total is still moving, so a proof of it means nothing.
        if period >= current {
            panic_with_error!(&env, VerifierError::PeriodNotClosed);
        }
        if period + MAX_PERIOD_LOOKBACK < current {
            panic_with_error!(&env, VerifierError::PeriodTooOld);
        }
        let last: Option<u64> = env
            .storage()
            .persistent()
            .get(&DataKey::LastPeriod(treasury.clone()));
        if let Some(l) = last {
            // Monotonic: this is the replay guard and it also stops an owner from
            // back-filling only the periods that happen to look good.
            if period <= l {
                panic_with_error!(&env, VerifierError::PeriodNotAdvancing);
            }
        }

        // ---- THE BINDING: the batch must account for what actually moved ----
        let spent = t.period_spent(&period);
        if spent < 0 {
            panic_with_error!(&env, VerifierError::SpendMismatch);
        }
        let spent_fr: BytesN<32> = public_bytes.slice(128..160).try_into().unwrap();
        if spent_fr != field_from_i128(&env, spent) {
            panic_with_error!(&env, VerifierError::SpendMismatch);
        }

        // ---- on-chain Groth16 pairing check ----
        let a: BytesN<64> = proof_bytes.slice(0..64).try_into().unwrap();
        let b: BytesN<128> = proof_bytes.slice(64..192).try_into().unwrap();
        let c: BytesN<64> = proof_bytes.slice(192..256).try_into().unwrap();
        let proof = Proof {
            a: Bn254G1Affine::from_bytes(a),
            b: Bn254G2Affine::from_bytes(b),
            c: Bn254G1Affine::from_bytes(c),
        };

        let mut pub_signals: Vec<Bn254Fr> = Vec::new(&env);
        let mut i: u32 = 0;
        while i < SIGNALS {
            let fr: BytesN<32> = public_bytes.slice(i * 32..i * 32 + 32).try_into().unwrap();
            pub_signals.push_back(Bn254Fr::from_bytes(fr));
            i += 1;
        }

        if !Self::verify_proof(env.clone(), proof, pub_signals).unwrap() {
            panic_with_error!(&env, VerifierError::InvalidProof);
        }

        // ---- EFFECTS: advance the period, then attest. Any panic above reverts. ----
        let key = DataKey::LastPeriod(treasury.clone());
        env.storage().persistent().set(&key, &period);
        env.storage().persistent().extend_ttl(
            &key,
            LAST_PERIOD_TTL_THRESHOLD,
            LAST_PERIOD_TTL_EXTEND_TO,
        );
        env.events()
            .publish((symbol_short!("attested"), treasury), (period, spent, root));
    }

    /// The last period this treasury attested to, if any.
    pub fn last_period(env: Env, treasury: Address) -> Option<u64> {
        env.storage()
            .persistent()
            .get(&DataKey::LastPeriod(treasury))
    }
}
